// Generates docs/API.md from the route source files so the reference cannot drift from the code.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const routesDir = join(root, 'apps/api/src/routes');
const appSrc = readFileSync(join(root, 'apps/api/src/app.ts'), 'utf8');

// file -> URL prefix, from the register() calls in app.ts
const reg = {};
for (const m of appSrc.matchAll(/register\((\w+)(?:, \{ prefix: '([^']*)' \})?\)/g)) reg[m[1]] = m[2] ?? '';
const importFile = {};
for (const m of appSrc.matchAll(/import \{([^}]+)\} from '\.\/routes\/(\w+)\.js'/g)) for (const n of m[1].split(',')) importFile[n.trim()] = m[2];
const prefixOf = {};
for (const [fn, prefix] of Object.entries(reg)) if (importFile[fn]) (prefixOf[importFile[fn]] ??= []).push(prefix);
// sub-plugins registered inside admin.ts inherit /api/admin
for (const f of ['adminCatalog', 'adminOps', 'adminSystem', 'adminReports']) prefixOf[f] = ['/api/admin'];

const area = (p) => p.startsWith('/api/admin') ? 'Staff (permission per route)' : p.startsWith('/api/vendor') ? 'Vendor' : p.includes('/driver') ? 'Driver' : 'Public / customer';
const rows = [];
for (const f of readdirSync(routesDir).filter((x) => x.endsWith('.ts'))) {
  const name = f.replace('.ts', '');
  const src = readFileSync(join(routesDir, f), 'utf8');
  const fileLoginHook = /addHook\('preHandler', requireLogin\)|requireUser\(req, reply\)/.test(src);
  for (const line of src.split('\n')) {
    const m = line.match(/app\.(get|post|put|patch|delete)(?:<[^(]*>)?\(\s*'([^']+)'/);
    if (!m) continue;
    const perms = [...line.matchAll(/requirePerm\(([^)]*)\)/g)].map((x) => x[1].replace(/'/g, '').trim());
    const login = fileLoginHook || line.includes('requireLogin') || perms.length > 0 || /\/(account|addresses|cart|orders|checkout|favourites|support|driver|vendor)/.test(m[2]);
    for (const prefix of prefixOf[name] ?? ['']) {
      const path = prefix + m[2];
      rows.push({ method: m[1].toUpperCase(), path: path.replace(/\/api\/api\//, '/api/'), auth: perms.length ? `permission: ${perms.join(' or ')}` : login ? 'signed in' : 'public', area: area(path), file: f });
    }
  }
}
rows.sort((a, b) => a.area.localeCompare(b.area) || a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
let out = '# API reference\n\n_Generated by `npm run docs:api` from the route source. Do not edit by hand._\n\n' +
  'All paths are under the API origin. Bodies are JSON and validated with zod; errors are `{ error, message, details? }`. Authentication is an HttpOnly session cookie. ' +
  'Checkout requires an `Idempotency-Key` header. Every money value is integer cents (CAD). Resource-level checks (own order, own store, own deliveries) are enforced inside each handler and covered by tests.\n';
let cur = '';
for (const r of rows) {
  if (r.area !== cur) { cur = r.area; out += `\n## ${cur}\n\n| Method | Path | Access | Source |\n|---|---|---|---|\n`; }
  out += `| ${r.method} | \`${r.path}\` | ${r.auth} | ${r.file} |\n`;
}
out += `\n${rows.length} endpoints.\n`;
writeFileSync(join(root, 'docs/API.md'), out);
console.log(`wrote docs/API.md (${rows.length} endpoints)`);
